// YoRHa Terminal -- translation build.
//   node tools/build_i18n.mjs
// 1. Extracts every English string (T/K/TN calls in main.js, games.js and breach3d.js, text in index.html, Pod lines
//    in podlines.js) into i18n/en.txt.
// 2. Checks each i18n/<code>.txt against it, line by line (same "## " sections, same line counts,
//    same {placeholders}, same Pod line kinds) and writes lang/<code>.js plus lang/index.js.
// Translation files are UTF-8 text; the generated .js files are plain ASCII (\u escapes).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const KINDS = ['Report', 'Proposal', 'Query', 'Alert', 'Hypothesis', 'Analysis', 'Warning', 'Confirmation', 'Summary'];

// ---------- 1. English catalog ----------

const unq = (s) => s.replace(/\\(.)/g, '$1');
function jsKeys(src) {
  const out = [];
  const re = /\b(?:T|K)\(\s*'((?:[^'\\]|\\.)*)'|\bTN\(\s*[^,()]+(?:\([^()]*\))?[^,()]*,\s*'((?:[^'\\]|\\.)*)'/g;
  let m;
  while ((m = re.exec(src))) out.push(unq(m[1] !== undefined ? m[1] : m[2]));
  return out;
}

function htmlKeys(src) {
  src = src.replace(/<head>[\s\S]*?<\/head>/i, '').replace(/<!--[\s\S]*?-->/g, '').replace(/<(svg|script|style)\b[\s\S]*?<\/\1>/gi, '');
  const out = [];
  const re = />([^<]+)</g;
  let m;
  while ((m = re.exec(src))) {
    const t = m[1].trim();
    if (/[A-Za-z]/.test(t)) out.push(t.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>'));
  }
  return out;
}

function loadPod() {
  const sandbox = { window: {} };
  vm.runInNewContext(rd('podlines.js'), sandbox);
  return sandbox.window.YoRHaPod;
}

// Walk the Pod bank in a fixed order: [sectionName, getter list] pairs that reach every string.
function podSections(bank) {
  const secs = [];
  const arr = (name, list) => secs.push({ name: name, get: () => list, set: (i, v) => { list[i] = v; } });
  for (const k of Object.keys(bank.idle)) arr('pod.idle.' + k, bank.idle[k]);
  for (const k of Object.keys(bank.time)) arr('pod.time.' + k, bank.time[k]);
  for (const k of Object.keys(bank.weekday)) arr('pod.weekday.' + k, bank.weekday[k]);
  for (const grp of ['chats', 'chatsLate']) {
    bank[grp].forEach((chat, i) => secs.push({
      name: 'pod.' + grp + '.' + i,
      get: () => chat.map((l) => l[1]),
      set: (j, v) => { chat[j][1] = v; }
    }));
  }
  bank.chars.forEach((c, i) => arr('pod.chars.' + i + ' (' + c.match + ')', c.lines));
  for (const k of Object.keys(bank.affiliation)) arr('pod.affiliation.' + k, bank.affiliation[k]);
  for (const k of Object.keys(bank.events)) {
    if (k === 'place') {
      for (const p of Object.keys(bank.events.place)) arr('pod.events.place.' + p, bank.events.place[p]);
    } else {
      arr('pod.events.' + k, bank.events[k]);
    }
  }
  const dk = Object.keys(bank.dates);
  secs.push({ name: 'pod.dates', get: () => dk.map((k) => bank.dates[k]), set: (i, v) => { bank.dates[dk[i]] = v; } });
  return secs;
}

const uiGroups = [
  ['ui.page', htmlKeys(rd('index.html'))],
  ['ui.terminal', jsKeys(rd('main.js'))],
  ['ui.games', jsKeys(rd('games.js'))],
  ['ui.breach', jsKeys(rd('breach3d.js'))]
];
const seen = new Set();
const ui = [];
for (const [name, keys] of uiGroups) {
  const fresh = keys.filter((k) => !seen.has(k) && seen.add(k));
  ui.push({ name: name, lines: fresh });
}
const enPod = loadPod();
const podSecs = podSections(enPod).map((s) => ({ name: s.name, lines: s.get().slice() }));
const sections = ui.concat(podSecs);

let en = '# YoRHa Terminal translation catalog (English source). Generated by tools/build_i18n.mjs -- do not edit.\n' +
  '# A translation file copies this layout: "@name" and "@html" header lines, then the same "## " sections\n' +
  '# with one translated line per English line, in the same order. Keep {placeholders} as they are.\n' +
  '# Plural keys use "|": give the forms your language needs (Russian: one|few|many; CJK: one form).\n' +
  '# Pod lines keep their English "Kind:" prefix (Report:, Proposal:, ...); only the text after it is translated.\n' +
  '@name English\n@html en\n';
for (const s of sections) en += '\n## ' + s.name + '\n' + s.lines.join('\n') + '\n';
fs.mkdirSync(path.join(ROOT, 'i18n'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'i18n', 'en.txt'), en);
const total = sections.reduce((n, s) => n + s.lines.length, 0);
console.log('[OK] i18n/en.txt: ' + sections.length + ' sections, ' + total + ' lines (' +
  ui.reduce((n, s) => n + s.lines.length, 0) + ' interface, ' + podSecs.reduce((n, s) => n + s.lines.length, 0) + ' Pod)');

// ---------- 2. translations ----------

function parse(file) {
  const out = { head: {}, secs: [] };
  let cur = null;
  fs.readFileSync(file, 'utf8').replace(/^\ufeff/, '').split(/\r?\n/).forEach((raw, i) => {
    const line = raw.replace(/\s+$/, '');
    if (!line.trim()) return;
    if (line.startsWith('## ')) {
      cur = { name: line.slice(3).trim(), lines: [], at: [] };
      out.secs.push(cur);
    } else if (line.startsWith('# ')) {
      // comment
    } else if (line.startsWith('@') && !cur) {
      const sp = line.indexOf(' ');
      out.head[line.slice(1, sp)] = line.slice(sp + 1).trim();
    } else if (cur) {
      cur.lines.push(line);
      cur.at.push(i + 1);
    }
  });
  return out;
}

const holes = (s) => (s.match(/\{\w+\}/g) || []).sort().join(',');
const asciiJs = (v) => JSON.stringify(v).replace(/[\u007f-\uffff]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));

const index = [{ code: 'en', name: 'English', html: 'en' }];
let failed = false;
const files = fs.readdirSync(path.join(ROOT, 'i18n')).filter((f) => /^[a-z]{2}\.txt$/.test(f) && f !== 'en.txt').sort();
fs.mkdirSync(path.join(ROOT, 'lang'), { recursive: true });

for (const f of files) {
  const code = f.slice(0, 2);
  const tr = parse(path.join(ROOT, 'i18n', f));
  const errs = [];
  if (tr.secs.length !== sections.length) errs.push('has ' + tr.secs.length + ' sections, English has ' + sections.length);
  const dict = {};
  const bank = JSON.parse(JSON.stringify(enPod));
  const bankSecs = podSections(bank);
  sections.forEach((s, si) => {
    const t = tr.secs[si];
    if (!t) return;
    if (t.name !== s.name) errs.push('section ' + (si + 1) + ' is "' + t.name + '", expected "' + s.name + '"');
    if (t.lines.length !== s.lines.length) {
      errs.push(s.name + ': ' + t.lines.length + ' lines, English has ' + s.lines.length + ' (section starts near line ' + (t.at[0] || '?') + ')');
      return;
    }
    s.lines.forEach((enLine, i) => {
      const line = t.lines[i];
      const where = f + ':' + t.at[i] + ' ';
      if (line.startsWith('@@TODO')) errs.push(where + 'not translated yet: ' + line);
      if (enLine.includes('|') && s.name.startsWith('ui.')) {
        const want = holes(enLine.split('|')[0]);
        for (const form of line.split('|')) if (holes(form) !== want) errs.push(where + 'plural form placeholders differ: ' + line);
      } else if (holes(enLine) !== holes(line)) {
        errs.push(where + 'placeholders ' + holes(line) + ' should be ' + holes(enLine) + ': ' + line);
      }
      if (s.name.startsWith('pod.')) {
        const ek = /^(\w+):\s/.exec(enLine), tk = /^(\w+):\s/.exec(line);
        if ((ek && ek[1]) !== (tk && tk[1])) errs.push(where + 'Pod kind must stay "' + (ek ? ek[1] : 'none') + ':" -- ' + line);
        else if (tk && !KINDS.includes(tk[1])) errs.push(where + 'unknown Pod kind ' + tk[1]);
      }
    });
    if (s.name.startsWith('ui.')) s.lines.forEach((k, i) => { dict[k] = t.lines[i]; });
    else {
      const b = bankSecs.find((x) => x.name === s.name);
      t.lines.forEach((v, i) => b.set(i, v));
    }
  });
  if (!tr.head.name || !tr.head.html) errs.push('missing @name or @html header');
  if (errs.length) {
    failed = true;
    console.log('[ERROR] ' + f + ': ' + errs.length + ' problem(s)');
    errs.slice(0, 25).forEach((e) => console.log('   ' + e));
    continue;
  }
  const js = '/* YoRHa Terminal -- ' + code + ' strings, generated by tools/build_i18n.mjs from i18n/' + f + '. Do not edit. */\n' +
    'window.YoRHaLang = window.YoRHaLang || {};\nwindow.YoRHaLang[' + asciiJs(code) + '] = ' + asciiJs({ ui: dict, pod: bank }) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'lang', code + '.js'), js);
  index.push({ code: code, name: tr.head.name, html: tr.head.html });
  console.log('[OK] lang/' + code + '.js (' + tr.head.name.replace(/[^\x20-\x7e]/g, '?') + '), ' + Math.round(js.length / 1024) + ' KB');
}

const order = ['en', 'zh', 'ja', 'ko', 'ru', 'de', 'fr', 'es', 'pt'];
index.sort((a, b) => (order.indexOf(a.code) + 99) % 99 - (order.indexOf(b.code) + 99) % 99);
fs.writeFileSync(path.join(ROOT, 'lang', 'index.js'),
  '/* YoRHa Terminal -- available languages, generated by tools/build_i18n.mjs. Do not edit. */\n' +
  'window.YoRHaLangIndex = ' + asciiJs(index) + ';\n');
console.log('[OK] lang/index.js: ' + index.map((l) => l.code).join(', '));
if (failed) process.exitCode = 1;
