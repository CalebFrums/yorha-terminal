// YoRHa Terminal -- install helper.
//   node tools/install.mjs          writes bundled.js (here and in the installed project)
//   node tools/install.mjs --copy   also copies the runtime files into the Wallpaper Engine project
// bundled.js lists the NieRCharacters folder that ships inside the installed project, so subscribers
// see characters before they choose a folder. project.json is never copied: the installed one (with the
// Workshop id and the user's edits) is the source of truth.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEST = 'C:\\Program Files (x86)\\Steam\\steamapps\\common\\wallpaper_engine\\projects\\myprojects\\yorha_terminal';
const FOLDER = 'NieRCharacters';
const IMAGE = /\.(png|jpe?g|webp|gif|bmp)$/i;

const charDir = path.join(DEST, FOLDER);
const files = fs.existsSync(charDir) ? fs.readdirSync(charDir).filter((f) => IMAGE.test(f)).sort((a, b) => a.localeCompare(b, 'en', { numeric: true })) : [];
for (const f of files) if (/[^\x20-\x7e]/.test(f)) throw new Error('[ERROR] non-ASCII file name: ' + f);
const js = '/* YoRHa Terminal -- character set shipped in ' + FOLDER + '/, generated by tools/install.mjs. Do not edit. */\n' +
  'window.YoRHaBundled = ' + JSON.stringify({ folder: FOLDER, files: files }, null, 1) + ';\n';
fs.writeFileSync(path.join(ROOT, 'bundled.js'), js);
console.log('[OK] bundled.js: ' + files.length + ' files');

if (process.argv.includes('--copy')) {
  const list = ['index.html', 'style.css', 'i18n.js', 'main.js', 'games.js', 'breach3d.js', 'podlines.js', 'bundled.js', 'preview.gif',
    'vendor/three.min.js', 'vendor/three.LICENSE.txt'];
  fs.mkdirSync(path.join(DEST, 'lang'), { recursive: true });
  fs.mkdirSync(path.join(DEST, 'vendor'), { recursive: true });
  for (const f of fs.readdirSync(path.join(ROOT, 'lang'))) if (f.endsWith('.js')) list.push('lang/' + f);
  for (const f of list) fs.copyFileSync(path.join(ROOT, f), path.join(DEST, f));
  console.log('[OK] copied ' + list.length + ' files to ' + DEST);
}
